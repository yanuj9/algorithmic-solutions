// Time Complexity: O(V^2 * E) for general graphs
// Time Complexity: O(E * sqrt(V)) for Unit Networks (Bipartite Matching)
struct Edge {
    int to;
    int capacity;
    int flow;
    int rev; // Index of the residual reverse edge
};

class Dinic {
private:
    int n;
    vector<vector<Edge>> adj;
    vector<int> level;
    vector<int> ptr;

    bool bfs(int s, int t) {
        fill(level.begin(), level.end(), -1);
        level[s] = 0;
        queue<int> q;
        q.push(s);
        while (!q.empty()) {
            int v = q.front();
            q.pop();
            for (const auto& edge : adj[v]) {
                if (edge.capacity - edge.flow > 0 && level[edge.to] == -1) {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    int dfs(int v, int t, int pushed) {
        if (pushed == 0 || v == t) return pushed;
        for (int& cid = ptr[v]; cid < adj[v].size(); ++cid) {
            auto& edge = adj[v][cid];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.capacity - edge.flow == 0) continue;
            int tr_pushed = dfs(tr, t, min(pushed, edge.capacity - edge.flow));
            if (tr_pushed == 0) continue;
            edge.flow += tr_pushed;
            adj[tr][edge.rev].flow -= tr_pushed;
            return tr_pushed;
        }
        return 0;
    }

public:
    // For 1-based indexing graph with N vertices, initialize with Dinic(N + 2)
    // This provides safe padding space for Source (0) and Sink (N + 1)
    Dinic(int n) : n(n), adj(n), level(n), ptr(n) {}

    void add_edge(int from, int to, int capacity) {
        adj[from].push_back({to, capacity, 0, (int)adj[to].size()});
        adj[to].push_back({from, 0, 0, (int)adj[from].size() - 1});
    }

    int max_flow(int s, int t) {
        int flow = 0;
        while (bfs(s, t)) {
            fill(ptr.begin(), ptr.end(), 0);
            while (int pushed = dfs(s, t, 1e9)) {
                flow += pushed;
            }
        }
        return flow;
    }
};

// -------------------- Solver --------------------
void solve() {
    ll n,m; cin>>n>>m;
    vector<vll> adj(n+1);
    vector<pll> edges;
    for(ll i=0; i<m; ++i) {
        ll u,v; cin>>u>>v;
        edges.push_back({u,v});
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    vll colors(n+1, -1);
    vll l;
    for(ll i=1; i<=n; ++i) {
        if(colors[i] == -1) {
            queue<ll> q;
            q.push(i);
            colors[i] = 0;
            l.push_back(i);
            while(!q.empty()) {
                ll u = q.front(); q.pop();
                for(auto v:adj[u]) {
                    if(colors[v] == -1) {
                        colors[v] = 1 - colors[u];
                        if(colors[v] == 0) l.push_back(v);
                        q.push(v);
                    }
                }
            }
        }
    }

    ll source = 0, sink = n+1;

    Dinic dinic(n+2);

    for(int i=1; i<=n; ++i) {
        if(colors[i] == 0) dinic.add_edge(source, i, 1);
        else dinic.add_edge(i, sink, 1);
    }

    for(auto [u,v]:edges) {
        if(colors[u] == 0) dinic.add_edge(u,v,1);
        else dinic.add_edge(v,u,1);
    }

    cout<<dinic.max_flow(source, sink);
}

